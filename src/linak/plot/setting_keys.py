def setting_values(values, *, gui=False, exclude=()):
    """Select settings before copying; never traverse a figure or plotted data."""
    allowed = GUI_SETTING_KEYS if gui else SETTING_KEYS
    return {key: value for key, value in values.items() if key in allowed and key not in exclude}


def copy_settings(values, *, gui=False, exclude=()):
    selected = setting_values(values, gui=gui, exclude=exclude)
    # Nested view snapshots must obey the same boundary as their parent.
    result = {}
    for key, value in selected.items():
        if key.endswith("_view_states") or key == "orientation_heatmap_states":
            result[key] = {
                name: copy_settings(
                    state,
                    gui=gui,
                    exclude=(
                        *exclude,
                        key,
                        "_profile_filter_options",
                        "data_contract",
                        "density_view_states",
                        "position_view_states",
                        "orientation_view_states",
                        "orientation_heatmap_states",
                    ),
                )
                for name, state in (value or {}).items()
                if isinstance(state, dict)
            }
        else:
            result[key] = deepcopy(value)
    return result
